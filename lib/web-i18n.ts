function localeToDictionary(language: string): Dictionary {
  if (language.startsWith("hi")) return hi;
  if (language.startsWith("ja")) return ja;
  if (language.startsWith("zh")) return zh;
  if (language.startsWith("es")) return es;
  if (language.startsWith("fr")) return fr;
  if (language.startsWith("ar")) return ar;
  if (language.startsWith("pt")) return pt;
  if (language.startsWith("ru")) return ru;
  if (language.startsWith("ur")) return ur;
  return en;
}

export function useI18n() {
  const language = useWebLanguage();
  const dictionary = useMemo(() => localeToDictionary(language), [language]);
  const t = (key: MessageKey): string => dictionary[key] ?? en[key] ?? key;
  return { t, language };
}
